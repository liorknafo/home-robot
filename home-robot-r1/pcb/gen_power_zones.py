def rect(u0, v0, u1, v1):
    p = pcbnew.SHAPE_POLY_SET(); p.NewOutline()
    for u, v in ((u0, v0), (u1, v0), (u1, v1), (u0, v1)): p.Append(MM(u), MM(v))
    return p


def octa(c, r):
    p = pcbnew.SHAPE_POLY_SET(); p.NewOutline(); R = r / math.cos(math.pi / 8)
    for k in range(8): p.Append(MM(c[0] + R * math.cos(math.pi / 8 + k * math.pi / 4)), MM(c[1] + R * math.sin(math.pi / 8 + k * math.pi / 4)))
    return p


def notch(c, side, edge, r=VIA):
    """An octagon round c plus a slot of its width out to the coordinate `edge` (side W / E: a u value, N / S: a v value)."""
    u, v = c
    n = octa(c, r)
    n.BooleanAdd({'W': rect(edge, v - r, u, v + r), 'E': rect(u, v - r, edge, v + r),
                  'N': rect(u - r, edge, u + r, v), 'S': rect(u - r, v, u + r, edge)}[side])
    return n


def circ(c, r, n=48):
    """An n-gon whose edges touch the circle of radius r round c from outside (keeps the whole circle out of the polygon)."""
    p = pcbnew.SHAPE_POLY_SET(); p.NewOutline(); R = r / math.cos(math.pi / n)
    for k in range(n): p.Append(MM(c[0] + R * math.cos(math.pi / n + 2 * math.pi * k / n)), MM(c[1] + R * math.sin(math.pi / n + 2 * math.pi * k / n)))
    return p


def cnotch(c, side, edge, r):
    """notch() with a near-exact circle (circ) instead of the octagon: for the pads at a corridor's binding neck."""
    u, v = c
    n = circ(c, r)
    n.BooleanAdd({'W': rect(edge, v - r, u, v + r), 'E': rect(u, v - r, edge, v + r),
                  'N': rect(u - r, edge, u + r, v), 'S': rect(u - r, v, u + r, edge)}[side])
    return n


CLEAR = BP.ZONE_CLEARANCE + 0.005   # mm: polygon to another net's pad at a binding neck (0.4 zone clearance + round-off)


def build(rects, cuts=()):
    s = pcbnew.SHAPE_POLY_SET()
    for r in rects: s.BooleanAdd(rect(*r))
    for c in cuts: s.BooleanSubtract(c)
    s.Simplify()
    assert s.OutlineCount() == 1 and s.HoleCount(0) == 0, (s.OutlineCount(), s.HoleCount(0) if s.OutlineCount() else None)
    o = s.Outline(0)
    pts = [(round(TOMM(o.CPoint(i).x), 2), round(TOMM(o.CPoint(i).y), 2)) for i in range(o.PointCount())]
    out = []
    for i, p in enumerate(pts):                                   # drop repeated and collinear points
        a, c = pts[i - 1], pts[(i + 1) % len(pts)]
        if p != a and abs((p[0] - a[0]) * (c[1] - a[1]) - (p[1] - a[1]) * (c[0] - a[0])) > 1e-6: out.append(p)
    return out


def pad(ref, pin): return B.pad_uv(ref, pin)
def gv(ref): return B.SMD_GND_VIAS[ref]


