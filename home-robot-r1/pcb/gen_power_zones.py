def fmt_pts(pts, indent):
    lines, cur = [], indent + 'poly=['
    for k, (u, v) in enumerate(pts):
        item = f'({u:g}, {v:g})' + (', ' if k < len(pts) - 1 else ']')
        if len(cur) + len(item) > 138: lines.append(cur.rstrip()); cur = indent + '      '
        cur += item
    lines.append(cur)
    return '\n'.join(lines)


def block():
    out = [BEGIN, 'POWER_ZONES = [']
    for entry, lanes, cuts in zones():
        head = ', '.join(f'{k}={v!r}' for k, v in entry.items())
        out.append(f'    dict({head},\n{fmt_pts(build(lanes, cuts), "         ")}),')
    out.append(']')
    out.append('GND_PATCHES = [')
    for pts in gnd_patches(): out.append(fmt_pts(pts, '    ').replace('    poly=', '    ', 1) + ',')
    out.append(']')
    items = [f'({n!r}, ({u:g}, {v:g}))' for n, (u, v) in STITCH]
    lines, cur = [], 'STITCH_VIAS = ['
    for k, it in enumerate(items):
        it += ', ' if k < len(items) - 1 else ']'
        if len(cur) + len(it) > 138: lines.append(cur.rstrip()); cur = '               '
        cur += it
    out.append('\n'.join(lines + [cur]))
    out.append(END)
    return '\n'.join(out)


def main():
    text = SPEC.read_text(encoding='utf-8')
    i, j = text.index(BEGIN), text.index(END) + len(END)
    new = text[:i] + block() + text[j:]
    if '--check' in sys.argv:
        if new != text:
            print('board_spec.py POWER_ZONES / GND_PATCHES / STITCH_VIAS are stale: run  $KPY pcb/gen_power_zones.py'); return 1
        print('board_spec.py generated block is current'); return 0
    SPEC.write_bytes(new.encode()); print('wrote', SPEC.name)
    return 0


